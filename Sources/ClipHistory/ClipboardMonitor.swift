import AppKit
import CryptoKit

/// A clipboard snapshot ready to be stored.
struct ClipCapture {
    var entry: ClipEntry
    var payload: ClipPayload
    var thumbnailPNG: Data?
}

/// Polls the general pasteboard for changes (macOS has no change notification).
@MainActor
final class ClipboardMonitor {
    var onCapture: ((ClipCapture) -> Void)?
    var isPaused = false

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after writing to the pasteboard ourselves so the write isn't recorded as a new copy.
    func skipCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused else { return }
        let source = NSWorkspace.shared.frontmostApplication
        if let capture = ClipboardReader.read(from: pasteboard, source: source) {
            onCapture?(capture)
        }
    }
}

enum ClipboardReader {
    /// Markers apps use to say "don't record this" (password managers, generated content).
    /// See http://nspasteboard.org
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    static let maxBytesPerType = 30 * 1024 * 1024
    static let maxBytesTotal = 60 * 1024 * 1024

    private static let richTypes: Set<String> = ["public.rtf", "public.html", "com.apple.flat-rtfd", "com.apple.webarchive"]
    private static let imageTypes: Set<String> = ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif", "com.adobe.pdf"]

    static func read(from pb: NSPasteboard, source: NSRunningApplication?) -> ClipCapture? {
        guard let items = pb.pasteboardItems, !items.isEmpty else { return nil }
        let allTypes = Set(items.flatMap { $0.types.map(\.rawValue) })
        guard allTypes.isDisjoint(with: ignoredTypes) else { return nil }

        var payload: ClipPayload = []
        var total = 0
        for item in items {
            var dict: [String: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type), data.count <= maxBytesPerType else { continue }
                dict[type.rawValue] = data
                total += data.count
            }
            if !dict.isEmpty { payload.append(dict) }
        }
        guard !payload.isEmpty, total <= maxBytesTotal else { return nil }

        var kind: ClipEntry.Kind
        var text: String
        var detail: String?
        var thumbnail: Data?
        var hashSource: Data

        let fileURLs = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        let string = pb.string(forType: .string)

        if !fileURLs.isEmpty {
            kind = .files
            text = fileURLs.map(\.lastPathComponent).joined(separator: "\n")
            detail = fileURLs.count == 1 ? fileURLs[0].deletingLastPathComponent().path : "\(fileURLs.count) files"
            thumbnail = fileThumbnail(for: fileURLs[0])
            hashSource = Data(fileURLs.map(\.path).joined(separator: "\n").utf8)
        } else if let string, !string.isEmpty {
            text = String(string.prefix(10_000))
            if isLink(string) {
                kind = .link
            } else if !allTypes.isDisjoint(with: richTypes) {
                kind = .richText
            } else {
                kind = .text
            }
            let lines = string.split(whereSeparator: \.isNewline).count
            detail = lines > 1 ? "\(lines) lines" : nil
            hashSource = Data(string.utf8)
        } else if !allTypes.isDisjoint(with: imageTypes), let image = NSImage(pasteboard: pb) {
            kind = .image
            text = "Image"
            if let rep = image.representations.first, rep.pixelsWide > 0 {
                detail = "\(rep.pixelsWide) × \(rep.pixelsHigh)"
            }
            thumbnail = ImageTools.thumbnailPNG(from: image)
            let firstImageType = imageTypes.first { allTypes.contains($0) } ?? ""
            hashSource = payload.lazy.compactMap { $0[firstImageType] }.first ?? Data()
        } else {
            kind = .other
            text = source?.localizedName.map { "Content from \($0)" } ?? "Unknown content"
            detail = allTypes.sorted().first
            hashSource = payload.flatMap { $0.sorted { $0.key < $1.key }.map(\.value) }.reduce(Data(), +)
        }

        let digest = SHA256.hash(data: Data(kind.rawValue.utf8) + hashSource)
        let entry = ClipEntry(
            id: UUID(),
            kind: kind,
            text: text,
            detail: detail,
            hasThumbnail: thumbnail != nil,
            sourceBundleID: source?.bundleIdentifier,
            sourceName: source?.localizedName,
            date: Date(),
            pinned: false,
            contentHash: digest.map { String(format: "%02x", $0) }.joined(),
            byteCount: total
        )
        return ClipCapture(entry: entry, payload: payload, thumbnailPNG: thumbnail)
    }

    private static func isLink(_ string: String) -> Bool {
        let s = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard s.count < 2048, !s.contains(where: \.isWhitespace),
              let url = URL(string: s), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https"].contains(scheme) && url.host != nil
    }

    private static func fileThumbnail(for url: URL) -> Data? {
        let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "gif", "heic", "tiff", "tif", "bmp", "webp"]
        if imageExtensions.contains(url.pathExtension.lowercased()),
           let attrs = try? FileManager.default.attributesOfItem(atPath: url.path),
           let size = attrs[.size] as? Int, size < 40 * 1024 * 1024,
           let image = NSImage(contentsOf: url) {
            return ImageTools.thumbnailPNG(from: image)
        }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        icon.size = NSSize(width: 64, height: 64)
        return ImageTools.thumbnailPNG(from: icon, maxPixels: CGSize(width: 128, height: 128))
    }
}

enum ImageTools {
    /// Downscales an image to fit `maxPixels` and encodes it as PNG.
    static func thumbnailPNG(from image: NSImage, maxPixels: CGSize = CGSize(width: 680, height: 260)) -> Data? {
        var source = image.size
        if let rep = image.representations.first, rep.pixelsWide > 0, rep.pixelsHigh > 0 {
            source = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        }
        guard source.width > 0, source.height > 0 else { return nil }
        let scale = min(1, maxPixels.width / source.width, maxPixels.height / source.height)
        let width = max(1, Int((source.width * scale).rounded()))
        let height = max(1, Int((source.height * scale).rounded()))
        guard let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        ) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        defer { NSGraphicsContext.restoreGraphicsState() }
        guard let context = NSGraphicsContext(bitmapImageRep: rep) else { return nil }
        NSGraphicsContext.current = context
        context.imageInterpolation = .high
        image.draw(in: NSRect(x: 0, y: 0, width: width, height: height), from: .zero, operation: .copy, fraction: 1)
        context.flushGraphics()
        return rep.representation(using: .png, properties: [:])
    }
}
